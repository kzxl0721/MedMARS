#          Surface Distance 核心计算（EDT + 法线查表）
#=================================================================================
##################################################################################

def compute_surface_distances(mask_gt: np.ndarray,
                               mask_pred: np.ndarray,
                               spacing_mm=(1.0, 1.0, 1.0)):
    """
    基于 Marching Cubes 法线查表 + EDT 计算表面距离。
    支持 2D（H,W）和 3D（D,H,W）mask。

    Returns:
        dict with keys:
            distances_gt_to_pred  : 1-D float array
            distances_pred_to_gt  : 1-D float array
            surfel_areas_gt       : 对应 GT 表面元面积 (mm^2)
            surfel_areas_pred     : 对应 Pred 表面元面积 (mm^2)
    """
    if mask_gt.ndim == 2:
        mask_gt    = mask_gt[np.newaxis, ...]
        mask_pred  = mask_pred[np.newaxis, ...]
        spacing_mm = (1.0,) + tuple(spacing_mm[:2])
    else:
        spacing_mm = tuple(spacing_mm)

    neighbour_code_to_surface_area = np.zeros(256)
    for code in range(256):
        normals = np.array(neighbour_code_to_normals[code])
        area = 0.0
        for nidx in range(normals.shape[0]):
            n = np.array([
                normals[nidx, 0] * spacing_mm[1] * spacing_mm[2],
                normals[nidx, 1] * spacing_mm[0] * spacing_mm[2],
                normals[nidx, 2] * spacing_mm[0] * spacing_mm[1],
            ])
            area += np.linalg.norm(n)
        neighbour_code_to_surface_area[code] = area

    mask_all = mask_gt | mask_pred
    if not mask_all.any():
        empty = np.array([])
        return {"distances_gt_to_pred": empty,
                "distances_pred_to_gt": empty,
                "surfel_areas_gt":      empty,
                "surfel_areas_pred":    empty}

    bbox_min = np.zeros(3, np.int64)
    bbox_max = np.zeros(3, np.int64)
    for ax, (ax1, ax2) in enumerate([(1,2),(0,2),(0,1)]):
        proj = np.max(np.max(mask_all, axis=ax2), axis=ax1)
        nz = np.nonzero(proj)[0]
        bbox_min[ax] = nz.min()
        bbox_max[ax] = nz.max()

    shape_crop = (bbox_max - bbox_min) + 2
    cropmask_gt   = np.zeros(shape_crop, np.uint8)
    cropmask_pred = np.zeros(shape_crop, np.uint8)
    sl = tuple(slice(bbox_min[i], bbox_max[i]+1) for i in range(3))
    cropmask_gt[0:-1, 0:-1, 0:-1]   = mask_gt[sl]
    cropmask_pred[0:-1, 0:-1, 0:-1] = mask_pred[sl]

    kernel = np.array([[[128, 64], [32, 16]],
                        [[  8,  4], [ 2,  1]]])
    code_gt   = scipy.ndimage.correlate(
        cropmask_gt.astype(np.uint8),   kernel, mode="constant", cval=0)
    code_pred = scipy.ndimage.correlate(
        cropmask_pred.astype(np.uint8), kernel, mode="constant", cval=0)

    borders_gt   = (code_gt   != 0) & (code_gt   != 255)
    borders_pred = (code_pred != 0) & (code_pred != 255)

    if borders_gt.any():
        distmap_gt = scipy.ndimage.distance_transform_edt(
            ~borders_gt, sampling=spacing_mm)
    else:
        distmap_gt = np.full(borders_gt.shape, np.inf)

    if borders_pred.any():
        distmap_pred = scipy.ndimage.distance_transform_edt(
            ~borders_pred, sampling=spacing_mm)
    else:
        distmap_pred = np.full(borders_pred.shape, np.inf)

    area_map_gt   = neighbour_code_to_surface_area[code_gt]
    area_map_pred = neighbour_code_to_surface_area[code_pred]

    dist_g2p  = distmap_pred[borders_gt]
    dist_p2g  = distmap_gt[borders_pred]
    area_gt   = area_map_gt[borders_gt]
    area_pred = area_map_pred[borders_pred]

    if dist_g2p.size > 0:
        idx = np.argsort(dist_g2p)
        dist_g2p = dist_g2p[idx]
        area_gt  = area_gt[idx]

    if dist_p2g.size > 0:
        idx = np.argsort(dist_p2g)
        dist_p2g  = dist_p2g[idx]
        area_pred = area_pred[idx]

    return {"distances_gt_to_pred": dist_g2p,
            "distances_pred_to_gt": dist_p2g,
            "surfel_areas_gt":      area_gt,
            "surfel_areas_pred":    area_pred}


def _compute_nsd_from_surface_distances(surface_distances: dict,
                                         tolerance_mm: float) -> float:
    """
    NSD = (Σ area_gt[d≤τ] + Σ area_pred[d≤τ]) / (Σ area_gt + Σ area_pred)
    """
    dist_g2p  = surface_distances["distances_gt_to_pred"]
    dist_p2g  = surface_distances["distances_pred_to_gt"]
    area_gt   = surface_distances["surfel_areas_gt"]
    area_pred = surface_distances["surfel_areas_pred"]

    total_gt   = float(np.sum(area_gt))
    total_pred = float(np.sum(area_pred))
    denom = total_gt + total_pred

    if denom == 0.0:
        return 1.0
    if total_gt == 0.0 or total_pred == 0.0:
        return 0.0

    overlap_gt   = float(np.sum(area_gt[dist_g2p   <= tolerance_mm]))
    overlap_pred = float(np.sum(area_pred[dist_p2g <= tolerance_mm]))

    return (overlap_gt + overlap_pred) / denom


