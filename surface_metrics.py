def _maybe_sigmoid(t: torch.Tensor) -> torch.Tensor:
    """仅在输出是 logit 时做 sigmoid（含负值或大于 1）。"""
    if t.min() < 0 or t.max() > 1:
        return torch.sigmoid(t)
    return t


def _to_bhw(tensor: torch.Tensor) -> torch.Tensor:
    """统一转为 (B, H, W)，兼容 (B,1,H,W) 和 (B,H,W)。"""
    t = tensor.detach().cpu().float()
    if t.dim() == 4:
        t = t.reshape(t.shape[0], t.shape[2], t.shape[3])
    return t


