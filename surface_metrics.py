def compute_surface_dice(pred: torch.Tensor,
                         target: torch.Tensor,
                         threshold: float = 0.5,
                         tolerance: float = 2.0,
                         spacing_mm=(1.0, 1.0)) -> float:
    """
    基于 Marching Cubes 法线查表 + EDT 的 Surface Dice（NSD）。

    Args:
        pred       : 模型输出，logit 或概率，shape (B,H,W) 或 (B,1,H,W)
        target     : Ground Truth，shape 同 pred
        threshold  : 二值化阈值，默认 0.5
        tolerance  : 表面容忍距离（像素），默认 2.0
        spacing_mm : 像素间距 (H方向, W方向)

    Returns:
        batch 内各样本 NSD 的宏平均；若所有样本均无法计算则返回 nan。
    """
    pred   = _maybe_sigmoid(_to_bhw(pred))
    target = _to_bhw(target)

    pred_bin   = (pred.numpy()   >= threshold).astype(bool)
    target_bin = (target.numpy() >= threshold).astype(bool)

    nsd_list = []
    for b in range(pred_bin.shape[0]):
        surf_dist = compute_surface_distances(
            mask_gt=target_bin[b],
            mask_pred=pred_bin[b],
            spacing_mm=spacing_mm
        )
        nsd = _compute_nsd_from_surface_distances(surf_dist, tolerance_mm=tolerance)
        nsd_list.append(nsd)

    return float(np.mean(nsd_list)) if nsd_list else float('nan')


def _get_surface_points(binary_mask: np.ndarray):
    """提取二值 mask 的表面点坐标（边界像素）。"""
    if binary_mask.sum() == 0:
        return None
    struct  = generate_binary_structure(binary_mask.ndim, 1)
    eroded  = binary_erosion(binary_mask, structure=struct, border_value=1)
    surface = binary_mask & ~eroded
    coords  = np.argwhere(surface)
    return coords if len(coords) > 0 else None

def compute_hd95(pred: torch.Tensor, target: torch.Tensor,
                 threshold: float = 0.5) -> float:
    """
    计算 HD95（95th percentile Hausdorff Distance）。

    Args:
        pred    : 模型输出，logit 或概率均可，shape (B,H,W) 或 (B,1,H,W)
        target  : Ground Truth，shape 同 pred
        threshold: 二值化阈值，默认 0.5
    Returns:
        batch 内各有效样本 HD95 的均值（像素单位）。
        若某样本 pred 或 target 全空则跳过；全部跳过返回 nan。
    """
    pred   = _maybe_sigmoid(_to_bhw(pred))
    target = _to_bhw(target)

    pred_bin   = (pred.numpy() >= threshold).astype(bool)
    target_bin = (target.numpy() >= threshold).astype(bool)

    hd95_list = []
    for b in range(pred_bin.shape[0]):
        pred_pts = _get_surface_points(pred_bin[b])
        gt_pts   = _get_surface_points(target_bin[b])

        if pred_pts is None or gt_pts is None:
            continue

        tree_gt   = cKDTree(gt_pts)
        tree_pred = cKDTree(pred_pts)

        dist_pg, _ = tree_gt.query(pred_pts)
        dist_gp, _ = tree_pred.query(gt_pts)

        all_dists = np.concatenate([dist_pg, dist_gp])
        hd95_list.append(float(np.percentile(all_dists, 95)))

    return float(np.mean(hd95_list)) if hd95_list else float('nan')